/**
 * Протокол тревожных сигналов (черновик — формулировки и шаблоны согласует специалист заказчицы).
 *
 * Свободный текст ученицы проверяется на признаки кризиса (мысли о самоповреждении) и
 * компенсаторного поведения (вызывание рвоты, слабительные, длительное голодание).
 * Распознавание — по словарю фраз: просто, предсказуемо и без отправки текста во внешние сервисы.
 * Это не диагностика: цель — вовремя показать контакты помощи и сообщить наставнику.
 */

export type SafetyLevel = 'high' | 'medium';

const HIGH: RegExp[] = [
  /не\s+(хочу|хочется)\s+жить/,
  /жить\s+не\s+(хочу|хочется)/,
  /хочу\s+умереть/,
  /лучше\s+бы\s+(меня|я)\s+(не\s+было|умерла|умер)/,
  /покончить\s+с\s+собой/,
  /свести\s+сч[её]ты\s+с\s+жизнью/,
  /суицид/,
  /самоубийств/,
  /(убить|убью)\s+себя/,
  /(порезать|резать|режу|порезала|порезалась|порезался)\s+(себя|руки|вены)/,
  /(причинить|причиню|причиняю)\s+себе\s+(вред|боль)/,
  /навредить\s+себе/,
  /селфхарм|self\s*-?\s*harm/,
  /нет\s+смысла\s+жить/,
  /исчезнуть\s+навсегда/,
];

const MEDIUM: RegExp[] = [
  /(вызвала|вызвал|вызвать|вызываю|вызывала)\s+рвоту/,
  /два\s+пальца\s+в\s+рот/,
  /слабительн/,
  /мочегонн/,
  /не\s+ела\s+(весь\s+день|целый\s+день|сутки|\d+\s+(дн|дня|дней|сут))/,
  /голодала\s+(весь|целый|\d)/,
  /наказ(ать|ываю|ала)\s+себя/,
  /ненавижу\s+(себя|сво[её]\s+тело)/,
];

function normalize(s: string): string {
  return s.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');
}

export interface SafetySignal {
  level: SafetyLevel;
  /** Совпавшие фрагменты — для наставника. */
  matches: string[];
}

export function detectSafetySignals(texts: Array<string | null | undefined>): SafetySignal | null {
  const text = normalize(texts.filter(Boolean).join(' \n '));
  if (!text.trim()) return null;
  const find = (list: RegExp[]) =>
    list.map((re) => re.exec(text)?.[0]).filter((m): m is string => !!m);
  const high = find(HIGH);
  if (high.length) return { level: 'high', matches: high };
  const medium = find(MEDIUM);
  if (medium.length) return { level: 'medium', matches: medium };
  return null;
}

